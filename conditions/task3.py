#bakery
cake_price=int(input("enter the cake price "))
if cake_price==1200:
    print("red velvet cake")
elif cake_price==1000:
    print("almond cake")
elif cake_price==800:
    print("choclate cake")
elif cake_price==600:
    print("butter scotch cake")
else:
    print("cake is not available")

